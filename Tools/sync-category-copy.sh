#!/usr/bin/env bash
# Writes App/Content/CategoryCopy.swift from the web's app/content/categories.ts (WEB_REF, default
# origin/main), so the category texts are the web's, word for word. Read-only on the web repo.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
repo="$(cd "$here/.." && pwd)"
WEB_REPO="$(cd "${WEB_REPO:-$repo/../quiz-game}" && pwd)"
REF="${WEB_REF:-origin/main}"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
git -C "$WEB_REPO" archive "$REF" app/content/categories.ts core/constants.ts | tar -x -C "$tmp"
printf '{ "type": "module" }\n' > "$tmp/package.json"
cat > "$tmp/dump.ts" <<'TS'
import { CATEGORY_COPY, HUB_COPY } from './app/content/categories.ts'
console.log(JSON.stringify({ categories: CATEGORY_COPY, hub: HUB_COPY }))
TS
(cd "$tmp" && "$WEB_REPO/node_modules/.bin/tsx" dump.ts) > "$tmp/copy.json"
python3 - "$tmp/copy.json" "$repo/App/Content/CategoryCopy.swift" "$(git -C "$WEB_REPO" rev-parse --short "$REF")" <<'PY'
import json, sys
data = json.load(open(sys.argv[1], encoding="utf-8"))
cases = {
    "Arte y Literatura": "artAndLiterature", "Historia y Geografía": "historyAndGeography", "Deportes": "sports",
    "Cine y televisión": "filmAndTV", "Ciencias": "science", "Lengua e Idiomas": "languages", "Música": "music",
}
def lit(s):
    return json.dumps(s, ensure_ascii=False)
def entry(c, indent):
    pad = " " * indent
    intro = ", ".join(lit(p) for p in c["intro"])
    return (f"CategoryCopy(\n{pad}    title: {lit(c['title'])},\n{pad}    heading: {lit(c['heading'])},\n"
            f"{pad}    blurb: {lit(c.get('blurb', ''))},\n{pad}    intro: [{intro}]\n{pad})")
out = ["// Generated by Tools/sync-category-copy.sh from the web's app/content/categories.ts (" + sys.argv[3] + ").",
       "// Do not edit by hand: change the web's file and run the script again.", "",
       "/// Texts of the category pages: title, heading, a one-line blurb and two intro paragraphs.",
       "struct CategoryCopy: Equatable {", "    let title: String", "    let heading: String", "    let blurb: String",
       "    let intro: [String]", "}", "", "func copy(for category: QuizCategory) -> CategoryCopy {", "    switch category {"]
for name, case in cases.items():
    out.append(f"    case .{case}:")
    out.append("        " + entry(data["categories"][name], 8))
out += ["    }", "}", "", "/// The hub of all categories.", "let hubCopy = " + entry(data["hub"], 0), ""]
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out))
print("wrote", sys.argv[2])
PY
